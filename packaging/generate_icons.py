#!/usr/bin/env python3
"""Draws the app icon and writes it in every format the three platforms need.

Standard library only. Run it from anywhere after changing the design:

    python3 packaging/generate_icons.py

Writes windows/fetcher.ico, macos/Fetcher.icns, linux/fetcher.png and
linux/app_icon_png.h next to this script.
"""

import math
import struct
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent

TOP = (0x4F, 0x6B, 0xF5)
BOTTOM = (0x7A, 0x3F, 0xE0)
WHITE = (255, 255, 255)
SOFT_WHITE = (205, 215, 255)

# All shapes are in a unit square.
OUTWARD_ARROW = [(0.22, 0.30), (0.56, 0.30), (0.56, 0.20), (0.80, 0.38),
                 (0.56, 0.56), (0.56, 0.46), (0.22, 0.46)]
INWARD_ARROW = [(0.78, 0.54), (0.78, 0.70), (0.44, 0.70), (0.44, 0.80),
                (0.20, 0.62), (0.44, 0.44), (0.44, 0.54)]


def polygon_distance(x, y, points):
    """Signed distance from (x, y) to a polygon: negative inside."""
    best = float("inf")
    inside = False
    j = len(points) - 1
    for i, (xi, yi) in enumerate(points):
        xj, yj = points[j]
        ex, ey = xj - xi, yj - yi
        wx, wy = x - xi, y - yi
        t = max(0.0, min(1.0, (wx * ex + wy * ey) / (ex * ex + ey * ey)))
        dx, dy = wx - ex * t, wy - ey * t
        best = min(best, dx * dx + dy * dy)
        if (yi > y) != (yj > y) and x < ex * (y - yi) / ey + xi:
            inside = not inside
        j = i
    distance = math.sqrt(best)
    return -distance if inside else distance


def rounded_square_distance(x, y, inset, radius):
    half = 0.5 - inset - radius
    qx, qy = abs(x - 0.5) - half, abs(y - 0.5) - half
    outside = math.hypot(max(qx, 0.0), max(qy, 0.0))
    return outside + min(max(qx, qy), 0.0) - radius


def coverage(distance, size):
    """Antialiased coverage of a pixel from a signed distance in unit space."""
    return max(0.0, min(1.0, 0.5 - distance * size))


def blend(under, over, amount):
    return tuple(u + (o - u) * amount for u, o in zip(under, over))


def render(size):
    rows = []
    for py in range(size):
        row = bytearray([0])  # PNG filter type: none
        y = (py + 0.5) / size
        for px in range(size):
            x = (px + 0.5) / size
            alpha = coverage(rounded_square_distance(x, y, 0.04, 0.2), size)
            if alpha <= 0:
                row += bytes(4)
                continue
            colour = blend(TOP, BOTTOM, (x * 0.3 + y * 0.7))
            colour = blend(colour, SOFT_WHITE, coverage(polygon_distance(x, y, INWARD_ARROW), size))
            colour = blend(colour, WHITE, coverage(polygon_distance(x, y, OUTWARD_ARROW), size))
            row += bytes(int(round(c)) for c in colour) + bytes([int(round(alpha * 255))])
        rows.append(bytes(row))
    return b"".join(rows)


def png(size):
    def chunk(kind, data):
        return (struct.pack(">I", len(data)) + kind + data +
                struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF))

    header = struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) +
            chunk(b"IDAT", zlib.compress(render(size), 9)) + chunk(b"IEND", b""))


def write_ico(path, images):
    entries = b""
    offset = 6 + 16 * len(images)
    for size, data in images:
        side = 0 if size >= 256 else size
        entries += struct.pack("<BBBBHHII", side, side, 0, 0, 1, 32, len(data), offset)
        offset += len(data)
    path.write_bytes(struct.pack("<HHH", 0, 1, len(images)) + entries +
                     b"".join(data for _, data in images))


def write_icns(path, images):
    kinds = {16: b"icp4", 32: b"icp5", 64: b"icp6", 128: b"ic07",
             256: b"ic08", 512: b"ic09", 1024: b"ic10"}
    body = b"".join(kinds[size] + struct.pack(">I", len(data) + 8) + data for size, data in images)
    path.write_bytes(b"icns" + struct.pack(">I", len(body) + 8) + body)


def write_header(path, data):
    lines = ["// Generated by packaging/generate_icons.py. Window icon for the Linux build.",
             "#pragma once", "", "static const unsigned char kAppIconPng[] = {"]
    for start in range(0, len(data), 16):
        lines.append("    " + ", ".join(str(b) for b in data[start:start + 16]) + ",")
    lines += ["};", ""]
    path.write_text("\n".join(lines))


def main():
    images = {size: png(size) for size in (16, 24, 32, 48, 64, 128, 256, 512, 1024)}
    write_ico(HERE / "windows" / "fetcher.ico",
              [(size, images[size]) for size in (16, 24, 32, 48, 64, 128, 256)])
    write_icns(HERE / "macos" / "Fetcher.icns",
               [(size, images[size]) for size in (16, 32, 64, 128, 256, 512, 1024)])
    (HERE / "linux" / "fetcher.png").write_bytes(images[256])
    write_header(HERE / "linux" / "app_icon_png.h", images[64])


if __name__ == "__main__":
    main()
